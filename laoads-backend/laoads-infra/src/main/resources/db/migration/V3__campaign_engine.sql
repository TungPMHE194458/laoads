CREATE TABLE LADS_SENDER_NUMBER (
  ID           NUMBER(19)          NOT NULL,
  CODE         VARCHAR2(32 CHAR)   NOT NULL,
  KIND         VARCHAR2(16 CHAR)   NOT NULL,
  DESCRIPTION  VARCHAR2(255 CHAR),
  ENABLED      NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_AT   TIMESTAMP           NOT NULL,
  CREATED_BY   VARCHAR2(64 CHAR),
  UPDATED_AT   TIMESTAMP,
  UPDATED_BY   VARCHAR2(64 CHAR),
  CONSTRAINT LADS_SENDER_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_SENDER_CODE_UK UNIQUE (CODE),
