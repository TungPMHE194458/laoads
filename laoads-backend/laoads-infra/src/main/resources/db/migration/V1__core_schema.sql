-- ============================================================================
-- V1 — LaoAds core schema (đợt 1)
--
-- Schema dùng chung với BOC (UBOC_*) + legacy → MỌI object của LaoAds prefix LADS_.
-- Flyway history riêng: LADS_FLYWAY_HISTORY. Không bao giờ chạm object không có prefix LADS_.
--
-- Target Oracle 11.2.0.4:
--   • không IDENTITY → SEQUENCE + Hibernate @SequenceGenerator (allocationSize=1)
--   • không BOOLEAN → NUMBER(1) + CHECK (0,1)
--   • VARCHAR2(n CHAR); lưu ý 11g giới hạn 4000 BYTE/VARCHAR2 → cột dài dùng ≤1000 CHAR hoặc CLOB
--   • tên object ≤ 30 ký tự
--   • TIMESTAMP lưu UTC (hibernate.jdbc.time_zone=UTC) — app luôn set giá trị, không dùng DEFAULT SYSTIMESTAMP
-- ============================================================================

-- 1. Người dùng ----------------------------------------------------------------
CREATE TABLE LADS_USER (
  ID             NUMBER(19)          NOT NULL,
  USERNAME       VARCHAR2(64 CHAR)   NOT NULL,
  PASSWORD_HASH  VARCHAR2(100 CHAR)  NOT NULL,
  FULL_NAME      VARCHAR2(255 CHAR),
  EMAIL          VARCHAR2(255 CHAR),
  PHONE          VARCHAR2(32 CHAR),
  SYSTEM_ROLE    VARCHAR2(16 CHAR)   DEFAULT 'USER' NOT NULL,
  STATUS         VARCHAR2(16 CHAR)   DEFAULT 'ACTIVE' NOT NULL,
  LAST_LOGIN_AT  TIMESTAMP,
  CREATED_AT     TIMESTAMP           NOT NULL,
  CREATED_BY     VARCHAR2(64 CHAR),
  UPDATED_AT     TIMESTAMP,
  UPDATED_BY     VARCHAR2(64 CHAR),
  CONSTRAINT LADS_USER_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_USER_USERNAME_UK UNIQUE (USERNAME),
  CONSTRAINT LADS_USER_ROLE_CK CHECK (SYSTEM_ROLE IN ('SUPER_ADMIN', 'USER')),
  CONSTRAINT LADS_USER_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'LOCKED'))
);
CREATE INDEX LADS_USER_EMAIL_IX ON LADS_USER (LOWER(EMAIL));
CREATE INDEX LADS_USER_PHONE_IX ON LADS_USER (PHONE);
CREATE SEQUENCE LADS_USER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- 2. Refresh token (lưu SHA-256, xoay vòng) ----------------------------------
CREATE TABLE LADS_REFRESH_TOKEN (
  ID           NUMBER(19)          NOT NULL,
  USER_ID      NUMBER(19)          NOT NULL,
  TOKEN_HASH   VARCHAR2(64 CHAR)   NOT NULL,
  AUTH_METHOD  VARCHAR2(16 CHAR)   DEFAULT 'PASSWORD' NOT NULL,
  EXPIRES_AT   TIMESTAMP           NOT NULL,
  CREATED_AT   TIMESTAMP           NOT NULL,
  REVOKED_AT   TIMESTAMP,
  REPLACED_BY  NUMBER(19),
  CLIENT_IP    VARCHAR2(64 CHAR),
  USER_AGENT   VARCHAR2(500 CHAR),
  CONSTRAINT LADS_RT_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_RT_HASH_UK UNIQUE (TOKEN_HASH),
  CONSTRAINT LADS_RT_USER_FK FOREIGN KEY (USER_ID) REFERENCES LADS_USER (ID) ON DELETE CASCADE,
  CONSTRAINT LADS_RT_METHOD_CK CHECK (AUTH_METHOD IN ('PASSWORD', 'VSA'))
);
CREATE INDEX LADS_RT_USER_IX ON LADS_REFRESH_TOKEN (USER_ID);
CREATE INDEX LADS_RT_EXPIRES_IX ON LADS_REFRESH_TOKEN (EXPIRES_AT);
CREATE SEQUENCE LADS_REFRESH_TOKEN_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- 3. Workspace -----------------------------------------------------------------
CREATE TABLE LADS_WORKSPACE (
  ID             NUMBER(19)           NOT NULL,
  CODE           VARCHAR2(32 CHAR)    NOT NULL,
  NAME           VARCHAR2(255 CHAR)   NOT NULL,
  DESCRIPTION    VARCHAR2(1000 CHAR),
  STATUS         VARCHAR2(16 CHAR)    DEFAULT 'ACTIVE' NOT NULL,
  CONTACT_NAME   VARCHAR2(255 CHAR),
  CONTACT_EMAIL  VARCHAR2(255 CHAR),
  CONTACT_PHONE  VARCHAR2(32 CHAR),
  CREATED_AT     TIMESTAMP            NOT NULL,
  CREATED_BY     VARCHAR2(64 CHAR),
  UPDATED_AT     TIMESTAMP,
  UPDATED_BY     VARCHAR2(64 CHAR),
  CONSTRAINT LADS_WS_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_WS_CODE_UK UNIQUE (CODE),
  CONSTRAINT LADS_WS_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'LOCKED'))
);
CREATE SEQUENCE LADS_WORKSPACE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- 4. Thành viên workspace (soft-delete bằng STATUS=REVOKED) ------------------
CREATE TABLE LADS_WORKSPACE_MEMBER (
  ID            NUMBER(19)         NOT NULL,
  WORKSPACE_ID  NUMBER(19)         NOT NULL,
  USER_ID       NUMBER(19)         NOT NULL,
  MEMBER_ROLE   VARCHAR2(16 CHAR)  NOT NULL,
  STATUS        VARCHAR2(16 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
  JOINED_AT     TIMESTAMP          NOT NULL,
  ADDED_BY      VARCHAR2(64 CHAR),
  UPDATED_AT    TIMESTAMP,
  UPDATED_BY    VARCHAR2(64 CHAR),
  REVOKED_AT    TIMESTAMP,
  REVOKED_BY    VARCHAR2(64 CHAR),
  CONSTRAINT LADS_WSM_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_WSM_WS_USER_UK UNIQUE (WORKSPACE_ID, USER_ID),
  CONSTRAINT LADS_WSM_WS_FK FOREIGN KEY (WORKSPACE_ID) REFERENCES LADS_WORKSPACE (ID),
  CONSTRAINT LADS_WSM_USER_FK FOREIGN KEY (USER_ID) REFERENCES LADS_USER (ID),
  CONSTRAINT LADS_WSM_ROLE_CK CHECK (MEMBER_ROLE IN ('OWNER', 'ADMIN', 'MEMBER')),
  CONSTRAINT LADS_WSM_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'REVOKED'))
);
CREATE INDEX LADS_WSM_USER_IX ON LADS_WORKSPACE_MEMBER (USER_ID);
CREATE SEQUENCE LADS_WORKSPACE_MEMBER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- 5. Ma trận role → permission (SUPER_ADMIN sửa được; seed ở V2) ------------
--    Không CHECK PERMISSION_CODE: danh mục permission nằm trong code (enum Permission), app validate.
CREATE TABLE LADS_ROLE_PERMISSION (
  ROLE_CODE        VARCHAR2(16 CHAR)  NOT NULL,
  PERMISSION_CODE  VARCHAR2(64 CHAR)  NOT NULL,
  UPDATED_AT       TIMESTAMP,
  UPDATED_BY       VARCHAR2(64 CHAR),
  CONSTRAINT LADS_ROLE_PERM_PK PRIMARY KEY (ROLE_CODE, PERMISSION_CODE),
  CONSTRAINT LADS_ROLE_PERM_ROLE_CK CHECK (ROLE_CODE IN ('OWNER', 'ADMIN', 'MEMBER'))
);

-- 6. Bảng giá + dòng giá ---------------------------------------------------------
CREATE TABLE LADS_PRICE_QUOTE (
  ID          NUMBER(19)           NOT NULL,
  NAME        VARCHAR2(255 CHAR)   NOT NULL,
  NOTE        VARCHAR2(1000 CHAR),
  STATUS      VARCHAR2(16 CHAR)    DEFAULT 'DRAFT' NOT NULL,
  CURRENCY    VARCHAR2(8 CHAR)     DEFAULT 'LAK' NOT NULL,
  LOCKED_AT   TIMESTAMP,
  LOCKED_BY   VARCHAR2(64 CHAR),
  ENDED_AT    TIMESTAMP,
  ENDED_BY    VARCHAR2(64 CHAR),
  CREATED_AT  TIMESTAMP            NOT NULL,
  CREATED_BY  VARCHAR2(64 CHAR),
  UPDATED_AT  TIMESTAMP,
  UPDATED_BY  VARCHAR2(64 CHAR),
  CONSTRAINT LADS_PQ_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_PQ_STATUS_CK CHECK (STATUS IN ('DRAFT', 'LOCKED', 'ENDED')),
  CONSTRAINT LADS_PQ_CURRENCY_CK CHECK (CURRENCY IN ('LAK'))
);
-- Tối đa 1 bảng LOCKED: function-based unique index (NULL không được index → chỉ dòng LOCKED bị ràng buộc)
CREATE UNIQUE INDEX LADS_PQ_ONE_LOCKED_UX ON LADS_PRICE_QUOTE (CASE WHEN STATUS = 'LOCKED' THEN 1 END);
CREATE INDEX LADS_PQ_CREATED_IX ON LADS_PRICE_QUOTE (CREATED_AT);
CREATE SEQUENCE LADS_PRICE_QUOTE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE LADS_PRICE_QUOTE_ITEM (
  ID                     NUMBER(19)         NOT NULL,
  QUOTE_ID               NUMBER(19)         NOT NULL,
  ACTION_TYPE            VARCHAR2(32 CHAR)  NOT NULL,
  UNIT_PRICE             NUMBER(19,4)       DEFAULT 0 NOT NULL,
  TIME_PRICE             NUMBER(19,4)       DEFAULT 0 NOT NULL,
  TIME_PRICE_PERCENTAGE  NUMBER(1)          DEFAULT 0 NOT NULL,
  SORT_ORDER             NUMBER(5)          DEFAULT 0 NOT NULL,
  CONSTRAINT LADS_PQI_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_PQI_QUOTE_ACTION_UK UNIQUE (QUOTE_ID, ACTION_TYPE),
  CONSTRAINT LADS_PQI_QUOTE_FK FOREIGN KEY (QUOTE_ID) REFERENCES LADS_PRICE_QUOTE (ID) ON DELETE CASCADE,
  CONSTRAINT LADS_PQI_PCT_CK CHECK (TIME_PRICE_PERCENTAGE IN (0, 1)),
  CONSTRAINT LADS_PQI_PRICE_CK CHECK (UNIT_PRICE >= 0 AND TIME_PRICE >= 0),
  CONSTRAINT LADS_PQI_ACTION_CK CHECK (ACTION_TYPE IN (
    'TOP_UP', 'ADD_MONEY', 'ADD_PROMOTION', 'ADD_DATA', 'ADD_SMS', 'ADD_CALL_MINUTES', 'ADD_PACKAGE',
    'REGISTER_CRBT', 'REGISTER_LAOTV',
    'NOTIFICATION_SMS', 'NOTIFICATION_EMAIL', 'NOTIFICATION_WHATSAPP', 'NOTIFICATION_USSD'))
);
CREATE SEQUENCE LADS_PRICE_QUOTE_ITEM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- 7. Nhật ký hệ thống ------------------------------------------------------------
--    Không CHECK ACTION_TYPE (danh sách mở: LOGIN/CREATE/UPDATE/DELETE/LOCK/UNLOCK/...).
--    Không FK WORKSPACE_ID/ACTOR_ID: log phải tồn tại kể cả khi đối tượng bị xoá.
CREATE TABLE LADS_AUDIT_LOG (
  ID            NUMBER(19)           NOT NULL,
  ACTOR         VARCHAR2(64 CHAR)    NOT NULL,
  ACTOR_ID      NUMBER(19),
  ACTION_TYPE   VARCHAR2(32 CHAR)    NOT NULL,
  ENTITY_TYPE   VARCHAR2(64 CHAR)    NOT NULL,
  ENTITY_ID     VARCHAR2(64 CHAR),
  WORKSPACE_ID  NUMBER(19),
  SUMMARY       VARCHAR2(1000 CHAR),
  DETAIL_JSON   CLOB,
  CLIENT_IP     VARCHAR2(64 CHAR),
  USER_AGENT    VARCHAR2(500 CHAR),
  REQUEST_ID    VARCHAR2(64 CHAR),
  CREATED_AT    TIMESTAMP            NOT NULL,
  CONSTRAINT LADS_AUDIT_PK PRIMARY KEY (ID)
);
CREATE INDEX LADS_AUDIT_CREATED_IX ON LADS_AUDIT_LOG (CREATED_AT);
CREATE INDEX LADS_AUDIT_WS_CREATED_IX ON LADS_AUDIT_LOG (WORKSPACE_ID, CREATED_AT);
CREATE INDEX LADS_AUDIT_ACTOR_IX ON LADS_AUDIT_LOG (ACTOR, CREATED_AT);
CREATE SEQUENCE LADS_AUDIT_LOG_SEQ START WITH 1 INCREMENT BY 1 CACHE 20;

-- 8. Comment --------------------------------------------------------------------
COMMENT ON TABLE LADS_USER IS 'LaoAds — tài khoản đăng nhập (local + map VSA theo username)';
COMMENT ON TABLE LADS_REFRESH_TOKEN IS 'LaoAds — refresh token (SHA-256), xoay vòng mỗi lần refresh';
COMMENT ON TABLE LADS_WORKSPACE IS 'LaoAds — workspace (đơn vị sử dụng)';
COMMENT ON TABLE LADS_WORKSPACE_MEMBER IS 'LaoAds — thành viên workspace (OWNER/ADMIN/MEMBER)';
COMMENT ON TABLE LADS_ROLE_PERMISSION IS 'LaoAds — ma trận vai trò workspace → permission';
COMMENT ON TABLE LADS_PRICE_QUOTE IS 'LaoAds — bảng giá (DRAFT/LOCKED/ENDED, tối đa 1 LOCKED)';
COMMENT ON TABLE LADS_PRICE_QUOTE_ITEM IS 'LaoAds — dòng giá theo loại hành động';
COMMENT ON TABLE LADS_AUDIT_LOG IS 'LaoAds — nhật ký thao tác hệ thống';
