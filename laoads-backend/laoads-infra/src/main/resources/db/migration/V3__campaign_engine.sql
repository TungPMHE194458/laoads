-- ───────────── Chiến dịch ─────────────
CREATE TABLE LADS_CAMPAIGN (
  ID                NUMBER(19)              NOT NULL,
  WORKSPACE_ID      NUMBER(19)              NOT NULL,
  CODE              VARCHAR2(32 CHAR)       NOT NULL,
  NAME              VARCHAR2(255 CHAR)      NOT NULL,
  DESCRIPTION       VARCHAR2(2000 CHAR),
  RUN_MODE          VARCHAR2(16 CHAR)       NOT NULL,
  CAMPAIGN_TYPE     VARCHAR2(16 CHAR)       NOT NULL,
  STATUS            VARCHAR2(20 CHAR)       NOT NULL,
  GROUP_ID          NUMBER(19),
  SEGMENT_ID        NUMBER(19),
  TARGET_COUNT      NUMBER(10) DEFAULT 0    NOT NULL,
  CHANNELS          VARCHAR2(100 CHAR),
  START_AT          TIMESTAMP,
  END_AT            TIMESTAMP,
  LANGUAGE          VARCHAR2(4 CHAR),
  TEST_ISDNS        VARCHAR2(4000 CHAR),
  DEFINITION_JSON   CLOB                    NOT NULL,
  EXPECTED_COST     NUMBER(18, 2) DEFAULT 0 NOT NULL,
  BUDGET_MAX        NUMBER(18, 2),
  REJECT_REASON     VARCHAR2(1000 CHAR),
  SENT_COUNT        NUMBER(10) DEFAULT 0    NOT NULL,
  DELIVERED_COUNT   NUMBER(10) DEFAULT 0    NOT NULL,
  FAILED_COUNT      NUMBER(10) DEFAULT 0    NOT NULL,
  OPEN_COUNT        NUMBER(10) DEFAULT 0    NOT NULL,
  CLICK_COUNT       NUMBER(10) DEFAULT 0    NOT NULL,
  CONVERSION_COUNT  NUMBER(10) DEFAULT 0    NOT NULL,
  REACHED_COUNT     NUMBER(10) DEFAULT 0    NOT NULL,
  SPENT             NUMBER(18, 2) DEFAULT 0 NOT NULL,
  UPLIFT            NUMBER(9, 4),
  NEXT_RUN_AT       TIMESTAMP,
  RUN_COUNT         NUMBER(6) DEFAULT 0     NOT NULL,
  SUBMITTED_AT      TIMESTAMP,
  APPROVED_AT       TIMESTAMP,
  APPROVED_BY       VARCHAR2(64 CHAR),
  COMPLETED_AT      TIMESTAMP,
  CREATED_AT        TIMESTAMP               NOT NULL,
  CREATED_BY        VARCHAR2(64 CHAR),
  UPDATED_AT        TIMESTAMP,
  UPDATED_BY        VARCHAR2(64 CHAR),
  VERSION           NUMBER(10) DEFAULT 0    NOT NULL,
  CONSTRAINT LADS_CAMPAIGN_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_CAMPAIGN_CODE_UK UNIQUE (CODE),
  CONSTRAINT LADS_CAMPAIGN_WS_FK FOREIGN KEY (WORKSPACE_ID) REFERENCES LADS_WORKSPACE (ID),
  CONSTRAINT LADS_CAMPAIGN_GROUP_FK FOREIGN KEY (GROUP_ID) REFERENCES LADS_CAMPAIGN_GROUP (ID),
  CONSTRAINT LADS_CAMPAIGN_SEG_FK FOREIGN KEY (SEGMENT_ID) REFERENCES LADS_SEGMENT (ID),
  CONSTRAINT LADS_CAMPAIGN_MODE_CK CHECK (RUN_MODE IN ('OFFICIAL', 'TEST')),
  CONSTRAINT LADS_CAMPAIGN_TYPE_CK CHECK (CAMPAIGN_TYPE IN ('STATIC', 'EVENT')),
  CONSTRAINT LADS_CAMPAIGN_STATUS_CK CHECK (STATUS IN ('DRAFT', 'PENDING_APPROVAL', 'SCHEDULED', 'RUNNING',
                                                       'PAUSED', 'COMPLETED', 'REJECTED', 'CANCELLED'))
);
CREATE INDEX LADS_CAMPAIGN_WS_STATUS_IX ON LADS_CAMPAIGN (WORKSPACE_ID, STATUS);
CREATE INDEX LADS_CAMPAIGN_NEXT_RUN_IX ON LADS_CAMPAIGN (STATUS, NEXT_RUN_AT);
CREATE INDEX LADS_CAMPAIGN_SEGMENT_IX ON LADS_CAMPAIGN (SEGMENT_ID);
CREATE INDEX LADS_CAMPAIGN_GROUP_IX ON LADS_CAMPAIGN (GROUP_ID);
CREATE SEQUENCE LADS_CAMPAIGN_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

