  CONSTRAINT LADS_SENDER_ENABLED_CK CHECK (ENABLED IN (0, 1))
);
CREATE SEQUENCE LADS_SENDER_NUMBER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

