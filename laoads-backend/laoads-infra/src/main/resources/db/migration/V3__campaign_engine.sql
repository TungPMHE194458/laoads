-- ───────────── Engine thực thi ─────────────
-- Mỗi lần chạy (NOW/ONCE: 1 lượt; RECURRING: mỗi chu kỳ 1 lượt; EVENT: 1 lượt "luồng sự kiện")
CREATE TABLE LADS_CAMPAIGN_RUN (
  ID            NUMBER(19)           NOT NULL,
  CAMPAIGN_ID   NUMBER(19)           NOT NULL,
  RUN_NO        NUMBER(6)            NOT NULL,
  STATUS        VARCHAR2(16 CHAR)    NOT NULL,
  SCHEDULED_AT  TIMESTAMP            NOT NULL,
  STARTED_AT    TIMESTAMP,
  FINISHED_AT   TIMESTAMP,
  TARGET_COUNT  NUMBER(10) DEFAULT 0 NOT NULL,
  CONSTRAINT LADS_CRUN_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_CRUN_CAMP_FK FOREIGN KEY (CAMPAIGN_ID) REFERENCES LADS_CAMPAIGN (ID) ON DELETE CASCADE,
  CONSTRAINT LADS_CRUN_STATUS_CK CHECK (STATUS IN ('RUNNING', 'COMPLETED', 'CANCELLED'))
);
CREATE UNIQUE INDEX LADS_CRUN_NO_UX ON LADS_CAMPAIGN_RUN (CAMPAIGN_ID, RUN_NO);
CREATE SEQUENCE LADS_CAMPAIGN_RUN_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Đối tượng nhận của một lượt: nhóm A/B (GROUP_KEY), nhóm đối chứng không nhận tin
CREATE TABLE LADS_CAMPAIGN_TARGET (
  ID            NUMBER(19)          NOT NULL,
  RUN_ID        NUMBER(19)          NOT NULL,
  CAMPAIGN_ID   NUMBER(19)          NOT NULL,
  ISDN          VARCHAR2(20 CHAR)   NOT NULL,
  GROUP_KEY     VARCHAR2(64 CHAR)   NOT NULL,
  IS_CONTROL    NUMBER(1) DEFAULT 0 NOT NULL,
  CONVERTED     NUMBER(1) DEFAULT 0 NOT NULL,
  CONVERTED_AT  TIMESTAMP,
  CREATED_AT    TIMESTAMP           NOT NULL,
  CONSTRAINT LADS_CTARGET_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_CTARGET_RUN_FK FOREIGN KEY (RUN_ID) REFERENCES LADS_CAMPAIGN_RUN (ID) ON DELETE CASCADE,
  CONSTRAINT LADS_CTARGET_CONTROL_CK CHECK (IS_CONTROL IN (0, 1)),
  CONSTRAINT LADS_CTARGET_CONV_CK CHECK (CONVERTED IN (0, 1))
);
CREATE UNIQUE INDEX LADS_CTARGET_RUN_ISDN_UX ON LADS_CAMPAIGN_TARGET (RUN_ID, ISDN);
CREATE INDEX LADS_CTARGET_CAMP_IX ON LADS_CAMPAIGN_TARGET (CAMPAIGN_ID, GROUP_KEY);
CREATE SEQUENCE LADS_CAMPAIGN_TARGET_SEQ START WITH 1 INCREMENT BY 1 CACHE 100;

-- Một tin / một hành động gửi tới một thuê bao. PREV_MESSAGE_ID: hành động trước trong chuỗi tuần tự.
CREATE TABLE LADS_CAMPAIGN_MESSAGE (
  ID               NUMBER(19)              NOT NULL,
  CAMPAIGN_ID      NUMBER(19)              NOT NULL,
  RUN_ID           NUMBER(19)              NOT NULL,
  TARGET_ID        NUMBER(19)              NOT NULL,
  ISDN             VARCHAR2(20 CHAR)       NOT NULL,
  GROUP_KEY        VARCHAR2(64 CHAR)       NOT NULL,
  ACTION_KEY       VARCHAR2(64 CHAR)       NOT NULL,
  ACTION_TYPE      VARCHAR2(32 CHAR)       NOT NULL,
  CHANNEL          VARCHAR2(16 CHAR)       NOT NULL,
  STATUS           VARCHAR2(16 CHAR)       NOT NULL,
  PREV_MESSAGE_ID  NUMBER(19),
  ATTEMPTS         NUMBER(3) DEFAULT 0     NOT NULL,
  DUE_AT           TIMESTAMP               NOT NULL,
  SENT_AT          TIMESTAMP,
  DELIVERED_AT     TIMESTAMP,
  OPENED_AT        TIMESTAMP,
  CLICKED_AT       TIMESTAMP,
  COST             NUMBER(14, 2) DEFAULT 0 NOT NULL,
  REFUNDED         NUMBER(1) DEFAULT 0     NOT NULL,
  PROVIDER_REF     VARCHAR2(64 CHAR),
  LAST_ERROR       VARCHAR2(500 CHAR),
  CONSTRAINT LADS_CMSG_PK PRIMARY KEY (ID),
  CONSTRAINT LADS_CMSG_RUN_FK FOREIGN KEY (RUN_ID) REFERENCES LADS_CAMPAIGN_RUN (ID) ON DELETE CASCADE,
  CONSTRAINT LADS_CMSG_STATUS_CK CHECK (STATUS IN ('PENDING', 'SENT', 'DELIVERED', 'FAILED', 'CANCELLED', 'SKIPPED')),
  CONSTRAINT LADS_CMSG_REFUNDED_CK CHECK (REFUNDED IN (0, 1))
);
CREATE INDEX LADS_CMSG_DUE_IX ON LADS_CAMPAIGN_MESSAGE (STATUS, DUE_AT);
CREATE INDEX LADS_CMSG_CAMP_IX ON LADS_CAMPAIGN_MESSAGE (CAMPAIGN_ID, STATUS);
CREATE INDEX LADS_CMSG_TARGET_IX ON LADS_CAMPAIGN_MESSAGE (TARGET_ID);
CREATE INDEX LADS_CMSG_SENT_IX ON LADS_CAMPAIGN_MESSAGE (SENT_AT);
CREATE SEQUENCE LADS_CAMPAIGN_MESSAGE_SEQ START WITH 1 INCREMENT BY 1 CACHE 100;

-- Link tracking: mỗi URL trong nội dung tin được thay bằng /api/v1/t/{TOKEN}
CREATE TABLE LADS_TRACKING_LINK (
  TOKEN        VARCHAR2(32 CHAR)    NOT NULL,
  MESSAGE_ID   NUMBER(19)           NOT NULL,
  CAMPAIGN_ID  NUMBER(19)           NOT NULL,
  TARGET_URL   VARCHAR2(2000 CHAR)  NOT NULL,
  CLICK_COUNT  NUMBER(10) DEFAULT 0 NOT NULL,
  FIRST_CLICK  TIMESTAMP,
  CREATED_AT   TIMESTAMP            NOT NULL,
  CONSTRAINT LADS_TRACKING_LINK_PK PRIMARY KEY (TOKEN),
  CONSTRAINT LADS_TLINK_MSG_FK FOREIGN KEY (MESSAGE_ID) REFERENCES LADS_CAMPAIGN_MESSAGE (ID) ON DELETE CASCADE
);
CREATE INDEX LADS_TLINK_MSG_IX ON LADS_TRACKING_LINK (MESSAGE_ID);

-- Sự kiện nhận qua API (kích hoạt chiến dịch EVENT)
